"""Versioned semantic catalog for measured evidence and linked context.

The catalog declares grains and field meanings. Physical readiness is resolved
against a verified package by :class:`hitlist.evidence_store.EvidenceStore`.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, replace

SCHEMA_VERSION = 16
FIELD_ROLES = frozenset(
    {
        "identity",
        "molecular_input",
        "biological_context",
        "target",
        "protocol",
        "provenance",
        "lineage",
        "relation",
        "annotation",
    }
)
VALUE_KINDS = frozenset({"identifier", "text", "number", "boolean", "category", "set", "sequence"})
EVIDENCE_KINDS = frozenset({"observation", "measurement", "projection", "relation", "context"})

NULL_STATES = {
    "unreported": "The source did not establish a value; absence is not implied.",
    "explicit_absence": "The source explicitly reports that the factor was absent.",
    "not_applicable": "The field has no meaning for this assay or material.",
    "unresolved": "Available claims do not resolve to one value.",
    "conflicting": "Source-backed claims disagree and both remain preserved.",
}


@dataclass(frozen=True)
class Field:
    name: str
    role: str
    value_kind: str
    meaning: str
    null_states: tuple[str, ...] = ("unreported",)


@dataclass(frozen=True)
class Evidence:
    name: str
    kind: str
    family: str
    grain: str
    native_artifact: str
    source_population: str
    endpoints: tuple[str, ...]
    fields: tuple[str, ...]
    index_required: tuple[str, ...]
    native_selector: str = ""
    assay_families: tuple[str, ...] = ()
    status: str = "v2_contract_only"
    materialized_artifact: str = ""
    index_required_any_of: tuple[tuple[str, ...], ...] = ()
    min_package_schema_version: int = 1
    required_appended_source: str | None = None


@dataclass(frozen=True)
class Task:
    name: str
    evidence: tuple[str, ...]
    required: tuple[str, ...]
    label_rule: str
    status: str = "v2_contract_only"
    required_any_of: tuple[tuple[str, ...], ...] = ()
    recipe_ids: tuple[str, ...] = ()


@dataclass(frozen=True)
class Baseline:
    population: str
    generation: str
    n_rows: int
    count_unit: str
    note: str


def _field(name, role, value_kind, meaning, *null_states):
    return Field(name, role, value_kind, meaning, null_states or ("unreported",))


